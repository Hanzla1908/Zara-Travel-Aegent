@router.get("/", response_model=list[AlertResponse])
async def list_alerts(
    user_id: str = Query(default="default"),
    db: AsyncSession = Depends(get_db),
):
    result = await db.execute(
        select(JobAlert)
        .where(JobAlert.user_id == user_id)
        .order_by(JobAlert.created_at.desc())
    )
    return result.scalars().all()


@router.post("/", response_model=AlertResponse, status_code=201)
async def create_alert(
    body: AlertCreate,
    user_id: str = Query(default="default"),
    db: AsyncSession = Depends(get_db),
):
    if body.frequency not in ("Hourly", "Daily", "Weekly"):
        raise HTTPException(status_code=422, detail="frequency must be Hourly, Daily, or Weekly")
    alert = JobAlert(user_id=user_id, **body.model_dump())
    db.add(alert)
    await db.commit()
    await db.refresh(alert)
    return alert


@router.patch("/{alert_id}", response_model=AlertResponse)
async def update_alert(
    alert_id: int,
    body: AlertUpdate,
    user_id: str = Query(default="default"),
    db: AsyncSession = Depends(get_db),
):
    result = await db.execute(
        select(JobAlert).where(JobAlert.id == alert_id, JobAlert.user_id == user_id)
    )
    alert = result.scalar_one_or_none()
    if not alert:
        raise HTTPException(status_code=404, detail="Alert not found")

    updates = body.model_dump(exclude_none=True)
    if "frequency" in updates and updates["frequency"] not in ("Hourly", "Daily", "Weekly"):
        raise HTTPException(status_code=422, detail="frequency must be Hourly, Daily, or Weekly")

    for field, value in updates.items():
        setattr(alert, field, value)

    await db.commit()
    await db.refresh(alert)
    return alert


@router.delete("/{alert_id}", status_code=200)
async def delete_alert(
    alert_id: int,
    user_id: str = Query(default="default"),
    db: AsyncSession = Depends(get_db),
):
    result = await db.execute(
        select(JobAlert).where(JobAlert.id == alert_id, JobAlert.user_id == user_id)
    )
    alert = result.scalar_one_or_none()
    if not alert:
        raise HTTPException(status_code=404, detail="Alert not found")

    await db.delete(alert)
    await db.commit()
    return {"message": "Alert deleted", "id": alert_id}


# ---------------------------------------------------------------------------
# Notification results
# ---------------------------------------------------------------------------

@router.get("/{alert_id}/results", response_model=list[AlertNotificationResponse])
async def list_results(
    alert_id: int,
    user_id: str  = Query(default="default"),
    unseen_only: bool = Query(default=False, description="Return only unseen notifications"),
    db: AsyncSession = Depends(get_db),
):
    """List notifications produced by an alert, newest first."""
    alert = await _get_alert_or_404(db, alert_id, user_id)
    stmt = (
        select(AlertNotification)
        .where(AlertNotification.alert_id == alert.id)
        .order_by(AlertNotification.created_at.desc())
    )
    if unseen_only:
        stmt = stmt.where(AlertNotification.seen == False)  # noqa: E712
    return (await db.execute(stmt)).scalars().all()


@router.patch("/{alert_id}/results/{notification_id}/seen", response_model=AlertNotificationResponse)
async def mark_seen(
    alert_id:        int,
    notification_id: int,
    user_id: str = Query(default="default"),
    db: AsyncSession = Depends(get_db),
):
    """Mark a single notification as seen."""
    await _get_alert_or_404(db, alert_id, user_id)
    result = await db.execute(
        select(AlertNotification).where(
            AlertNotification.id == notification_id,
            AlertNotification.alert_id == alert_id,
        )
    )
    notif = result.scalar_one_or_none()
    if not notif:
        raise HTTPException(status_code=404, detail="Notification not found")
    notif.seen = True
    await db.commit()
    await db.refresh(notif)
    return notif


# ---------------------------------------------------------------------------
# On-demand check
# ---------------------------------------------------------------------------

@router.post("/{alert_id}/check")
async def run_check(
    alert_id: int,
    user_id: str = Query(default="default"),
    db: AsyncSession = Depends(get_db),
):
    """
    Trigger an immediate check for this alert.

    This will call the external job sources listed in the alert's `sources`
    field if any are configured.  The user's explicit call to this endpoint
    serves as confirmation of that external action.
    """
    from app.services.alert_checker import check_alert

    alert = await _get_alert_or_404(db, alert_id, user_id)
    new_count = await check_alert(db, alert)
    return {
        "message":        "Check complete",
        "new_matches":    new_count,
        "last_checked_at": alert.last_checked_at,
    }


# ---------------------------------------------------------------------------
# Helper
# ---------------------------------------------------------------------------

async def _get_alert_or_404(db: AsyncSession, alert_id: int, user_id: str) -> JobAlert:
    result = await db.execute(
        select(JobAlert).where(JobAlert.id == alert_id, JobAlert.user_id == user_id)
    )
    alert = result.scalar_one_or_none()
    if not alert:
        raise HTTPException(status_code=404, detail="Alert not found")
    return alert
